#!/usr/bin/env node
'use strict';

/**
 * Generates the synthetic example XML files in examples/.
 *
 * The output mirrors the structure of an exported ServiceNow update set
 * (<unload> -> sys_remote_update_set + sys_update_xml rows whose <payload> holds
 * a serialized <record_update>). All names, ids and scripts are invented.
 *
 *   node scripts/generate-examples.js
 */

const fs = require('node:fs');
const path = require('node:path');

const OUT_DIR = path.join(__dirname, '..', 'examples');
const STAMP = '2026-01-15 10:00:00';
const AUTHOR = 'synthetic.developer';

let counter = 0;
/** Obviously synthetic sys_ids: c0ffee00 followed by a zero-padded counter. */
function synthId() {
  counter += 1;
  return 'c0ffee00' + counter.toString(16).padStart(24, '0');
}

function esc(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function fieldXml(name, value) {
  if (value && typeof value === 'object') {
    return `<${name} display_value="${esc(value.display)}">${esc(value.value)}</${name}>`;
  }
  return `<${name}>${esc(value)}</${name}>`;
}

function recordXml(table, fields, action = 'INSERT_OR_UPDATE') {
  const body = Object.entries(fields)
    .map(([k, v]) => fieldXml(k, v))
    .join('');
  return `<${table} action="${action}">${body}</${table}>`;
}

const GLOBAL = { value: 'global', display: 'Global' };
const DEMO_SCOPE = { value: 'c0ffee00aaaaaaaaaaaaaaaaaaaaaa01', display: 'x_demo_fieldsvc' };

function businessRule({ name, table, when, script, scope = GLOBAL }) {
  return {
    table: 'sys_script',
    target: name,
    type: 'Business Rule',
    fields: {
      name,
      collection: table,
      when,
      order: '100',
      active: 'true',
      advanced: 'true',
      action_insert: 'true',
      action_update: 'true',
      script,
      sys_class_name: 'sys_script',
      sys_id: synthId(),
      sys_scope: scope,
    },
  };
}

function clientScript({ name, table, type, field = '', script }) {
  return {
    table: 'sys_script_client',
    target: name,
    type: 'Client Script',
    fields: { name, table, type, field_name: field, ui_type: '0', active: 'true', script, sys_id: synthId(), sys_scope: GLOBAL },
  };
}

function scriptInclude({ name, script, scope = GLOBAL, clientCallable = false }) {
  const apiName = scope === GLOBAL ? `global.${name}` : `${scope.display}.${name}`;
  return {
    table: 'sys_script_include',
    target: name,
    type: 'Script Include',
    fields: {
      name,
      api_name: apiName,
      client_callable: String(clientCallable),
      access: 'package_private',
      active: 'true',
      script,
      sys_id: synthId(),
      sys_scope: scope,
    },
  };
}

function uiAction({ name, table, client, onclick = '', script }) {
  return {
    table: 'sys_ui_action',
    target: name,
    type: 'UI Action',
    fields: {
      name,
      table,
      action_name: name.toLowerCase().replace(/\W+/g, '_'),
      client: String(client),
      onclick,
      form_button: 'true',
      active: 'true',
      script,
      sys_id: synthId(),
      sys_scope: GLOBAL,
    },
  };
}

/**
 * Serialize an update set. `cdata` controls how each payload is embedded:
 * real exports are entity-escaped; CDATA is accepted too.
 */
function updateSetXml(name, description, items) {
  const setId = synthId();
  const rows = items.map((item, idx) => {
    const action = item.action || 'INSERT_OR_UPDATE';
    const inner =
      `<?xml version="1.0" encoding="UTF-8"?>\n` +
      `<record_update table="${item.table}">${recordXml(item.table, item.fields, action)}</record_update>`;
    const payload = idx % 2 === 0 ? `<![CDATA[${inner}]]>` : esc(inner);
    return [
      `<sys_update_xml action="INSERT_OR_UPDATE">`,
      `<action>${action}</action>`,
      `<application display_value="Global">global</application>`,
      `<category>customer</category>`,
      `<name>${item.table}_${item.fields.sys_id}</name>`,
      `<payload>${payload}</payload>`,
      `<remote_update_set display_value="${esc(name)}">${setId}</remote_update_set>`,
      `<sys_created_by>${AUTHOR}</sys_created_by>`,
      `<sys_created_on>${STAMP}</sys_created_on>`,
      `<sys_id>${synthId()}</sys_id>`,
      `<target_name>${esc(item.target)}</target_name>`,
      `<type>${item.type}</type>`,
      `<update_domain>global</update_domain>`,
      `</sys_update_xml>`,
    ].join('\n');
  });

  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    `<!-- Synthetic example generated by scripts/generate-examples.js. Not taken from any real instance. -->`,
    `<unload unload_date="${STAMP}">`,
    `<sys_remote_update_set action="INSERT_OR_UPDATE">`,
    `<application display_value="Global">global</application>`,
    `<description>${esc(description)}</description>`,
    `<name>${esc(name)}</name>`,
    `<state>loaded</state>`,
    `<sys_id>${setId}</sys_id>`,
    `</sys_remote_update_set>`,
    ...rows,
    '</unload>',
    '',
  ].join('\n');
}

