function singleRecordUnload() {
  const si = scriptInclude({
    name: 'InventorySync',
    scope: DEMO_SCOPE,
    script: `var InventorySync = Class.create();
InventorySync.prototype = {
    initialize: function() {},

    syncAll: function() {
        var parts = new GlideRecord('x_demo_fieldsvc_part');
        parts.query();
        gs.print('parts to sync: ' + parts.getRowCount());
    },

    type: 'InventorySync'
};`,
  });
  // "Export XML" output keeps scripts readable inside CDATA sections.
  const fields = Object.entries(si.fields).map(([k, v]) =>
    k === 'script' ? `  <script><![CDATA[${v}]]></script>` : '  ' + fieldXml(k, v)
  );
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- Synthetic example generated by scripts/generate-examples.js. Not taken from any real instance. -->',
    `<unload unload_date="${STAMP}">`,
    `<sys_script_include action="INSERT_OR_UPDATE">`,
    ...fields,
    '</sys_script_include>',
    '</unload>',
    '',
  ].join('\n');
}

